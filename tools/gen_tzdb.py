#!/usr/bin/env python3
"""Generate stan-claw/main/tzdb.h: every IANA time zone name and its POSIX TZ
rule, for the board to set its clock from the zone its internet connection
reports ("America/Toronto" -> "EST5EDT,M3.2.0,M11.1.0").

The rule is the footer of each TZif (version 2+) file: the last line, which
says how the zone keeps time after its recorded transitions -- exactly what
newlib's setenv("TZ") understands.

    python3 tools/gen_tzdb.py > stan-claw/main/tzdb.h
"""
import os
import sys
import zoneinfo

ROOT = next(p for p in zoneinfo.TZPATH if os.path.isdir(p))
rows = []
for name in sorted(zoneinfo.available_timezones()):
    path = os.path.join(ROOT, name)
    try:
        data = open(path, "rb").read()
    except OSError:
        continue
    if not data.startswith(b"TZif") or data[4:5] < b"2":
        continue
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii", "replace")
    if not footer or "/" in name and name.split("/")[0] in ("posix", "right", "Etc") and name != "Etc/UTC":
        continue
    rows.append((name, footer))
print("/* Generated by tools/gen_tzdb.py from the system's IANA time zone files -- do not edit by hand.")
print(f" * {len(rows)} zones, sorted by name for tz_posix's binary search. */")
print("static const struct { const char *iana, *posix; } TZDB[] = {")
for n, f in rows:
    print(f'    {{ "{n}", "{f}" }},')
print("};")
sys.stderr.write(f"{len(rows)} zones\n")
